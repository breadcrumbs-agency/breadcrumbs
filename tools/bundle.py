#!/usr/bin/env python3
"""Build an installable bundle of one breadcrumbs part, from the parts at their checked-out commits.

    python tools/bundle.py hermes OUTDIR [--parts DIR]
    python tools/bundle.py claude OUTDIR [--parts DIR]
    python tools/bundle.py hermes OUTDIR --publish      (also: commit the bundle on the `release` branch of the part and push it)

Why: Hermes installs a plugin from one repository and installs only the PyPI names that its pyproject.toml lists
(a direct URL is not managed), and Claude Code runs a plugin from one folder. The parts are separate repositories
(common, spacegraph, hermes, claude), so a plugin cannot import its layers from them. The bundle is the plugin folder
with the layers it needs copied under `lib/`, and a first line in `__init__.py` that puts `lib/` on `sys.path`.
The source stays in the parts; a bundle is generated, never edited (a file `BUNDLE.json` says from which commits).

--parts DIR: the folder that holds the part folders (default: the folder above this repository).
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SKIP = shutil.ignore_patterns("__pycache__", "*.pyc", ".git", ".DS_Store", ".venv", "*.egg-info", "build", "dist")

PRELUDE = '''import os as _os
import sys as _sys

_LIB = _os.path.join(_os.path.dirname(_os.path.abspath(__file__)), "lib")  # the layers under this plugin (tools/bundle.py)
if _os.path.isdir(_LIB) and _LIB not in _sys.path:
    _sys.path.insert(0, _LIB)
'''


def head(part):
    """The commit of a part, with a mark if its tree is not clean."""
    def git(*args):
        return subprocess.run(["git", "-C", part, *args], capture_output=True, text=True).stdout.strip()
    sha = git("rev-parse", "HEAD")
    return {"commit": sha, "clean": git("status", "--porcelain", "--untracked-files=no") == ""}


def copy_package(part, package, out):
    src = os.path.join(part, package)
    if not os.path.isdir(src):
        sys.exit("bundle: %s has no folder %s" % (part, package))
    shutil.copytree(src, os.path.join(out, "lib", package), ignore=SKIP)


def after_docstring(text):
    """Split a module text after its leading docstring."""
    import ast
    tree = ast.parse(text)
    first = tree.body[0] if tree.body else None
    if isinstance(first, ast.Expr) and isinstance(getattr(first, "value", None), ast.Constant) \
            and isinstance(first.value.value, str):
        lines = text.splitlines(keepends=True)
        return "".join(lines[:first.end_lineno]), "".join(lines[first.end_lineno:])
    return "", text


def hermes(parts, out):
    root = os.path.join(parts, "breadcrumbs-hermes")
    common, spacegraph = (os.path.join(parts, name) for name in ("breadcrumbs-common", "breadcrumbs-spacegraph"))
    shutil.copytree(root, out, ignore=SKIP, dirs_exist_ok=True)
    copy_package(common, "breadcrumbs", out)
    copy_package(spacegraph, "breadcrumbs_spacegraph", out)
    entry = os.path.join(out, "__init__.py")
    with open(entry, encoding="utf-8") as f:
        doc, rest = after_docstring(f.read())
    with open(entry, "w", encoding="utf-8") as f:
        doc = doc.replace("come from breadcrumbs-common and breadcrumbs-spacegraph, which pyproject.toml names.",
                          "are copied under lib/ from breadcrumbs-common and breadcrumbs-spacegraph (tools/bundle.py).")
        f.write(doc + "\n" + PRELUDE + rest)
    # One dependency, as the monolith had: the CRC32C instruction. No [build-system] and no extra: Hermes would
    # build the plugin itself into its environment (tests/test_plugin_entry.py).
    with open(os.path.join(out, "pyproject.toml"), "w", encoding="utf-8") as f:
        f.write(
            "# Generated by tools/bundle.py from breadcrumbs-hermes, breadcrumbs-common and breadcrumbs-spacegraph\n"
            "# (see BUNDLE.json). One dependency: google-crc32c, so the CRC32C uses the CPU instruction (CPython only;\n"
            "# GraalPy runs the pure loop). The layers are under lib/. With a [build-system] table or an extra, Hermes\n"
            "# would also build the plugin itself into its environment, so this file declares neither.\n"
            "[project]\n"
            'name = "breadcrumbs"\n'
            'version = "%s"\n'
            'description = "Content-addressed breadcrumb memory for Hermes: exact provenance, zoom levels 0..1, steady-state context."\n'
            'requires-python = ">=3.11"\n'
            'license = "MIT"\n'
            'license-files = ["LICENSE"]\n'
            "dependencies = [\"google-crc32c>=1.5,<2; platform_python_implementation == 'CPython'\"]\n\n"
            "[tool.setuptools]\n"
            'packages = ["breadcrumbs_hermes"]\n\n'
            "[tool.setuptools.package-data]\n"
            'breadcrumbs_hermes = ["skills/*/SKILL.md"]\n' % version(root))
    return {"breadcrumbs-hermes": head(root), "breadcrumbs-common": head(common),
            "breadcrumbs-spacegraph": head(spacegraph)}


def version(part):
    with open(os.path.join(part, "pyproject.toml"), encoding="utf-8") as f:
        for line in f:
            if line.startswith("version"):
                return line.split("=", 1)[1].strip().strip('"')
    return "0.0.0"


def claude(parts, out):
    root = os.path.join(parts, "breadcrumbs-claude")
    common = os.path.join(parts, "breadcrumbs-common")
    shutil.copytree(root, out, ignore=SKIP, dirs_exist_ok=True)
    copy_package(common, "breadcrumbs", out)
    # The bundle is also a one-plugin marketplace: /plugin marketplace add breadcrumbs-agency/breadcrumbs-claude#release
    with open(os.path.join(out, ".claude-plugin", "marketplace.json"), "w", encoding="utf-8") as f:
        json.dump({"name": "breadcrumbs-agency", "owner": {"name": "breadcrumbs-agency"},
                   "plugins": [{"name": "breadcrumbs", "source": "./",
                                "description": "Content-addressed memory for Claude Code (MCP server: find, open, zoom, trail)."}]},
                  f, indent=2)
        f.write("\n")
    return {"breadcrumbs-claude": head(root), "breadcrumbs-common": head(common)}


BUILDERS = {"hermes": hermes, "claude": claude}
PART = {"hermes": "breadcrumbs-hermes", "claude": "breadcrumbs-claude"}
INSTALL = {
    "hermes": "hermes plugins install breadcrumbs-agency/breadcrumbs-hermes --ref %s",
    "claude": "/plugin marketplace add breadcrumbs-agency/breadcrumbs-claude#release   (then: /plugin install breadcrumbs@breadcrumbs-agency)",
}


def publish(target, bundle, parts, sources):
    """Commit the bundle as the next commit of the part's `release` branch and push it. History of the branch is kept:
    each release is a child of the last (Hermes installs one exact commit; the commit is printed)."""
    import tempfile
    origin = subprocess.run(["git", "-C", os.path.join(parts, PART[target]), "remote", "get-url", "origin"],
                            capture_output=True, text=True, check=True).stdout.strip()
    with tempfile.TemporaryDirectory(prefix="bundle-release-") as work:
        def git(*a, check=True):
            return subprocess.run(["git", "-C", work, "-c", "user.name=breadcrumbs-agency",
                                   "-c", "user.email=breadcrumbs-agency@users.noreply.github.com", *a],
                                  capture_output=True, text=True, check=check)
        cloned = subprocess.run(["git", "clone", "-q", "--branch", "release", "--single-branch", origin, work],
                                capture_output=True, text=True).returncode == 0
        if not cloned:
            git("init", "-q", "-b", "release")
            git("remote", "add", "origin", origin)
        for name in os.listdir(work):
            if name != ".git":
                path = os.path.join(work, name)
                shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
        shutil.copytree(bundle, work, dirs_exist_ok=True)
        git("add", "-A")
        if git("status", "--porcelain").stdout.strip():
            note = ", ".join("%s %s" % (name, info["commit"][:7]) for name, info in sources.items())
            git("commit", "-q", "-m", "release: the %s plugin bundle (%s)" % (target, note))
            git("push", "-q", "origin", "release")
        sha = git("rev-parse", "HEAD").stdout.strip()
    print("published %s release %s" % (PART[target], sha))
    print("install:  " + INSTALL[target] % sha if target == "hermes" else "install:  " + INSTALL[target])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("target", choices=sorted(BUILDERS))
    ap.add_argument("out")
    ap.add_argument("--parts", default=os.path.dirname(os.path.dirname(HERE)))
    ap.add_argument("--publish", action="store_true", help="commit the bundle on the release branch of the part and push")
    args = ap.parse_args(argv)
    out = os.path.abspath(args.out)
    if os.path.exists(out) and os.listdir(out):
        sys.exit("bundle: %s is not empty" % out)
    sources = BUILDERS[args.target](os.path.abspath(args.parts), out)
    with open(os.path.join(out, "BUNDLE.json"), "w", encoding="utf-8") as f:
        json.dump({"target": args.target, "sources": sources}, f, indent=2)
        f.write("\n")
    dirty = [name for name, info in sources.items() if not info["clean"]]
    print("bundle %s -> %s" % (args.target, out))
    for name, info in sources.items():
        print("  %-24s %s%s" % (name, info["commit"][:8], "" if info["clean"] else "  (tree not clean)"))
    if dirty:
        print("bundle: not clean: %s" % ", ".join(dirty), file=sys.stderr)
    if args.publish:
        if dirty:
            sys.exit("bundle: not publishing from a tree that is not clean")
        publish(args.target, out, os.path.abspath(args.parts), sources)


if __name__ == "__main__":
    main()
